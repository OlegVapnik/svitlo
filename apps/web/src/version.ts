/**
 * Версия приложения, видимая пользователю: X.Y.Z.
 *
 * Правила её повышения (см. tools/bump-version.sh и AGENTS.md):
 *   X — крупное: смена архитектуры, новый экрана��, переезд на другой источник данных,
 *       изменение формата данных, обратно несовместимое изменение API;
 *   Y — среднее: новая функциональность внутри существующего экрана, новый эндпоинт,
 *       заметное улучшение поведения;
 *   Z — мелкое: исправление ошибки, вёрстка, тексты, обновление зависимостей.
 *
 * Почему версия видна прямо в интерфейсе, а не только в сборщике: при разборе «на телефоне
 * ничего не изменилось» первым делом смотришь, какая версия установлена. Метка сборки
 * (`__BUILD_ID__`) показывает время сборки, а версия — смысловое поколение приложения.
 */
export const APP_VERSION = '2.2.0';

/** Человекочитаемое представление для UI и логов. */
export function appVersionLabel(buildId?: string): string {
  return buildId ? `v${APP_VERSION} · build ${buildId}` : `v${APP_VERSION}`;
}