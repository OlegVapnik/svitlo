import { TAB_ITEMS, isNavItemActive } from '../components/layout/nav-items.js';

/**
 * Направление перехода между табами — чистый расчёт без DOM (проверяется тестом).
 *
 * Зачем направление нужно: контент приходит из той стороны, куда «уехала» лента. Свайп влево
 * открывает следующий таб, и новый экран должен въехать справа — тогда жест читается как
 * перемещение ленты, а не как мгновенная подмена картинки (именно этого не хватало: «сенсор
 * работает, но переход резкий»).
 *
 * Направление выводится из порядка табов, а не из жеста: тап по нижней панели ведёт туда же,
 * куда свайп, и обязан выглядеть так же. Жест лишь ускоряет выбор, но не меняет правило.
 */

/** `next` — таб правее текущего (контент въезжает справа), `prev` — левее, `none` — без сдвига. */
export type TabDirection = 'next' | 'prev' | 'none';

/** Индекс таба, которому принадлежит адрес; -1 — служебный экран вне нижней навигации. */
export function tabIndexOf(pathname: string): number {
  return TAB_ITEMS.findIndex((item) => isNavItemActive(pathname, item.to));
}

/**
 * Куда движется интерфейс при переходе `from` → `to`.
 *
 * `none` — если хотя бы один из адресов не принадлежит табу (служебные экраны: импорт графика,
 * выбор области) или это тот же таб (переключение подразделов через `?tab=`). В этом случае
 * контент просто проявляется на месте: сдвиг здесь подсказывал бы несуществующее «соседство».
 */
export function resolveTabDirection(from: string, to: string): TabDirection {
  const previous = tabIndexOf(from);
  const next = tabIndexOf(to);
  if (previous === -1 || next === -1 || previous === next) return 'none';
  return next > previous ? 'next' : 'prev';
}
