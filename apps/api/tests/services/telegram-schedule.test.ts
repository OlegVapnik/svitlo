import { describe, expect, test } from 'vitest';
import {
  TELEGRAM_OFF_STATE,
  mergeTelegramSlots,
  parseTelegramScheduleText,
  resolveScheduleDate,
  type TelegramScheduleSlot,
} from '../../src/services/telegram-schedule.service.js';

/**
 * Імпорт ГПВ з публічного Telegram-каналу оператора (t.me/s/chernigivoblenergo).
 *
 * Зачем тест: це єдиний перевірений канал «черга + час» без Turnstile (див. HANDOFF §18.9): метод
 * `info_schedule` — заглушка, а `info_schedule_part` закритий капчею, яку ми не обходимо. Тому саме
 * цей парсер робить `schedule_slots` непорожнім, і його не можна ламати мовчки.
 *
 * Тексти в фікстурах — реальні публічні пости каналу (без персональних даних), скорочені до частини
 * з графіком; повні тексти лежать у `telegram_posts` (post_id вказані в коментарях).
 */
const post = (publishedAt: string) => new Date(publishedAt);

/** post 5514 (2026-10-09T13:45:47Z): дві черги в одному пості. */
const POST_5514 = 'За вказівкою НЕК "Укренерго", маємо зміни у Графіку погодинних відключень (ГПВ) на 9 жовтня ☝️.🕗 З 16:40 до 18:30 додатково відключається черга 6/2.🕗 З 18:30 до 22:00 додатково відключається черга 3/2. ⚠️ Якщо ситуація в енергосистемі змінюватиметься, графік коригуватиметься.';
/** post 5511 (2026-10-09T10:01:28Z): «до HH:MM» = відключення від початку доби. */
const POST_5511 = '📊 За вказівкою НЕК "Укренерго", маємо зміни у Графіку погодинних відключень (ГПВ) на 9 жовтня .🕗 До 15:00 додатково відключаються черга 2/2.‼️ Якщо ситуація в енергосистемі змінюватиметься, графік коригуватиметься.';
/** post 5492 (2026-10-06T14:44:12Z): інтервал, що закінчується опівночі. */
const POST_5492 = 'За вказівкою НЕК "Укренерго", маємо зміни у Графіку погодинних відключень (ГПВ) на 6 жовтня ☝️.🕗 З 18:00 до 20:30 додатково відключається черга 5/2. 🕗 З 20:30 до 00:00 додатково відключається черга 2/1. ⚠️ Якщо ситуація в енергосистемі змінюватиметься, графік коригуватиметься.';
/** post 5519 (2026-10-10T17:56:31Z): анонс «діятиме ГПВ» без жодного інтервалу. */
const POST_5519 = 'За вказівкою НЕК "Укренерго", 11 жовтня в області діятиме Графік погодинних відключень (ГПВ) ☝️.⚠️ Якщо ситуація в енергосистемі змінюватиметься, графік коригуватиметься, тож просимо слідкувати за нашими офіційними ресурсами.';

describe('parseTelegramScheduleText', () => {
  test('дістає кілька черг з одного поста разом із датою з тексту', () => {
    const slots = parseTelegramScheduleText(POST_5514, post('2026-10-09T13:45:47Z'));
    expect(slots).toHaveLength(2);
    expect(slots).toEqual(expect.arrayContaining([
      { queue: '6/2', date: '2026-10-09', timeFrom: '16:40', timeTo: '18:30' },
      { queue: '3/2', date: '2026-10-09', timeFrom: '18:30', timeTo: '22:00' },
    ]));
  });

  test('«до 15:00 … черга 2/2» = відключення з початку доби', () => {
    expect(parseTelegramScheduleText(POST_5511, post('2026-10-09T10:01:28Z'))).toEqual([
      { queue: '2/2', date: '2026-10-09', timeFrom: '00:00', timeTo: '15:00' },
    ]);
  });

  test('інтервал до «00:00» зберігається як кінець доби (не як порожній)', () => {
    const slots = parseTelegramScheduleText(POST_5492, post('2026-10-06T14:44:12Z'));
    expect(slots).toEqual(expect.arrayContaining([
      { queue: '5/2', date: '2026-10-06', timeFrom: '18:00', timeTo: '20:30' },
      { queue: '2/1', date: '2026-10-06', timeFrom: '20:30', timeTo: '00:00' },
    ]));
  });

  test('анонс без інтервалів не дає вигаданих слотів', () => {
    expect(parseTelegramScheduleText(POST_5519, post('2026-10-10T17:56:31Z'))).toEqual([]);
  });

  test('черга без часу і некоректний час не дають слотів', () => {
    expect(parseTelegramScheduleText('Зміни в ГПВ: чергу 3/2 відключать, деталі на сайті.', post('2026-10-09T10:00:00Z'))).toEqual([]);
    expect(parseTelegramScheduleText('З 25:00 до 26:00 додатково відключається черга 1/1.', post('2026-10-09T10:00:00Z'))).toEqual([]);
  });
});

describe('resolveScheduleDate', () => {
  test('без дати в тексті бере київську дату публікації (21:30Z = уже наступна доба)', () => {
    expect(resolveScheduleDate('🕗 З 10:00 до 12:00 додатково відключається черга 1/1.', post('2026-10-09T21:30:00Z'))).toBe('2026-10-10');
  });

  test('«завтра» = доба після публікації', () => {
    expect(resolveScheduleDate('Завтра діятиме ГПВ, о 10:00 відключать чергу 2/2.', post('2026-10-09T13:45:47Z'))).toBe('2026-10-10');
  });

  test('«на 9 жовтня» перекриває дату публікації', () => {
    expect(resolveScheduleDate(POST_5514, post('2026-10-09T13:45:47Z'))).toBe('2026-10-09');
  });

  test('грудень → січень не ламає рік (текст про минулий місяць = наступний рік)', () => {
    expect(resolveScheduleDate('З 10:00 до 12:00 відключається черга 1/1 на 2 січня.', post('2026-12-30T10:00:00Z'))).toBe('2027-01-02');
  });
});

describe('mergeTelegramSlots', () => {
  const slot = (timeFrom: string, timeTo: string): TelegramScheduleSlot => ({ queue: '2/2', date: '2026-10-09', timeFrom, timeTo });

  test('стик і перекриття однієї черги стають одним інтервалом', () => {
    expect(mergeTelegramSlots([slot('10:00', '12:00'), slot('12:00', '14:00')])).toEqual([slot('10:00', '14:00')]);
    expect(mergeTelegramSlots([slot('10:00', '12:00'), slot('11:00', '13:00')])).toEqual([slot('10:00', '13:00')]);
  });

  test('різні черги не змішуються', () => {
    const merged = mergeTelegramSlots([slot('10:00', '12:00'), { ...slot('10:00', '12:00'), queue: '3/2' }]);
    expect(merged).toHaveLength(2);
  });
});

describe('легенда станів', () => {
  test('черга, яку «додатково відключають», = стан 3 оператора', () => {
    expect(TELEGRAM_OFF_STATE).toEqual({ code: 3, name: 'Відключення', color: '#E33535' });
  });
});
