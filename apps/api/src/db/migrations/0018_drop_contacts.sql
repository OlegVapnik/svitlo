-- Удаление справочника контактов оператора.
--
-- Проект больше не зависит от контактов: телефон колл-центра в интерфейсе убран,
-- отдельного раздела «Контакти» больше нет, а данные собирались вручную и со временем
-- устаревали (номера и ссылки меняются на стороне оператора, а у нас — нет).
--
-- Почему новая миграция, а не правка 0010_operator_contacts.sql: применённые миграции
-- не трогаем — на них уже записан чек-лист, и их правка ломает историю базы у всех,
-- кто её разворачивал.
--
-- Идемпотентно: IF EXISTS делает повторный прогон безопасным.
DROP TABLE IF EXISTS contacts;