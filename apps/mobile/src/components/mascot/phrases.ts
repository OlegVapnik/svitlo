/** Фрази сплячої маскотки внизу головного екрана — пул спільний для будь-якого стану. */
const SLEEP_PHRASES: readonly string[] = [
  'Пограй зі мною… Тут сумно без тебе 💔',
  'zzz… буди мене, коли дадуть світло 😴',
  'Я лежу, а графік сам не прочитається… 💤',
  'Мені сниться електромережа без аварій ⚡',
  'Трохи посплю, поки ти зайнятий справами 💤',
  'Полежимо разом — так темрява не страшна 🫂',
];

/**
 * Випадкова фраза з пулу, без повтору попередньої (exclude).
 * guard обмежує цикл, якщо пул раптом складається з однієї фрази.
 */
export function pickPhrase(mood: MascotMood, powerState: PowerState, exclude?: string): string {
  const pool: readonly string[] = mood === 'sleep' ? SLEEP_PHRASES : THINK_PHRASES[powerState];
  const fallback = 'Тапни ще раз — щось я замовкла 🙈';
  if (pool.length === 0) return fallback;

  let phrase = pool[Math.floor(Math.random() * pool.length)];
  let guard = 0;
  while (phrase === exclude && guard < 8) {
    phrase = pool[Math.floor(Math.random() * pool.length)];
    guard += 1;
  }
  return phrase;
}
