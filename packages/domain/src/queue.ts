/**
 * Код черги: нормалізація запису, який приходить від різних джерел.
 *
 * Одна черга в різних джерелах пишеться по-різному: «1.1», «1-1», «1 / 1», « 1/1 ».
 * Домен фіксує один канонічний вигляд — «1/1», — щоб ключі черг збігалися і в базі,
 * і в UI, і в парсерах.
 *
 * Не плутати з `queueFromGroupKey` зі `schedule-utils.ts`: та функція розбирає строгий
 * формат групи зеркала (`2.2` → `2/2`) і повертає `null` на будь-чому іншому, бо там
 * потрібен саме валідований код. Тут — «вичистити те, що вже схоже на код».
 */
export function normalizeQueue(value: string | null | undefined): string {
  return String(value ?? '')
    .replace(/\s+/gu, '')
    .replace(/[.\-]+/gu, '/')
    .replace(/\/{2,}/gu, '/');
}
