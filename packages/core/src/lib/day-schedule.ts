import type { ScheduleIntervalUtc } from '@svitlo/shared';

/**
 * Одна київська доба графіка — спільний тип для «перетин груп» і PNG-картки.
 *
 * Раніше цей тип жив у `power-windows.ts` разом із планувальником вікон. Планувальник
 * прибрано (він радив «коли увімкнути прилад» за орієнтовним графіком, а графік може
 * змінитися), але `DaySchedule` і код 2 лишилися потрібними: без них порівняння черг і
 * картка не відрізняли б «світло є» від «можливо вимкнуть».
 */

/**
 * Код оператора «можливо вимкнуть»: не відключення, але й не гарантоване світло.
 *
 * Не плутати з `MIRROR_OFF_CODE` з `@svitlo/domain`: там теж 2, але це сирий код
 * дзеркала «світла немає» (стан комірки оператора), а тут — стан у нашій моделі UI
 * («можливо відключать»). Числа збігаються випадково; зливати ці константи не можна,
 * інакше зміна одного коду мовчки переозначить інший.
 */
export const UNCERTAIN_STATE_CODE = 2;

/** Одна київська доба графіка. */
export interface DaySchedule {
  /** Київська дата YYYY-MM-DD. */
  date: string;
  intervals: ScheduleIntervalUtc[];
  /**
   * Оператор опублікував ГПВ на цю добу (навіть якщо годин відключень у ній немає).
   * Без цього прапорця порожній `intervals` — це «даних немає», а не «світло цілу добу».
   */
  covered?: boolean;
}
